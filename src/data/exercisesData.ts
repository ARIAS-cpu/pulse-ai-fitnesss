export function matchExerciseTag(exercise: GymExercise, tagId: string): boolean {
  if (!tagId || tagId === 'all' || tagId === 'todos') return true;
  const tag = tagId.toLowerCase();
  
  if (exercise.tags && exercise.tags.some(t => t.toLowerCase() === tag)) return true;
  if (tag === 'chest' && (exercise.muscleGroup === 'pecho' || exercise.name.toLowerCase().includes('pecho') || exercise.name.toLowerCase().includes('banca'))) return true;
  if (tag === 'back' && (exercise.muscleGroup === 'espalda' || exercise.name.toLowerCase().includes('espalda') || exercise.name.toLowerCase().includes('remo') || exercise.name.toLowerCase().includes('dominada'))) return true;
  if (tag === 'legs' && (exercise.muscleGroup === 'piernas' || exercise.name.toLowerCase().includes('sentadilla') || exercise.name.toLowerCase().includes('prensa') || exercise.name.toLowerCase().includes('femoral') || exercise.name.toLowerCase().includes('gemelo'))) return true;
  if (tag === 'shoulders' && (exercise.muscleGroup === 'hombros' || exercise.name.toLowerCase().includes('hombro') || exercise.name.toLowerCase().includes('militar') || exercise.name.toLowerCase().includes('lateral'))) return true;
  if (tag === 'arms' && (exercise.muscleGroup === 'biceps' || exercise.muscleGroup === 'triceps' || exercise.muscleGroup === 'brazos' || exercise.name.toLowerCase().includes('curl') || exercise.name.toLowerCase().includes('tríceps'))) return true;
  if (tag === 'core' && (exercise.muscleGroup === 'core' || exercise.name.toLowerCase().includes('abdominal') || exercise.name.toLowerCase().includes('plancha'))) return true;
  if (tag === 'cardio' && (exercise.muscleGroup === 'funcional' || exercise.equipment === 'cardio')) return true;

  return false;
}

